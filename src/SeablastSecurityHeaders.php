<?php

declare(strict_types=1);

namespace Seablast\Seablast;

use Seablast\Seablast\Exceptions\SeablastConfigurationException;

/** Immutable response policy; create once per request after configuration closures have run. */
class SeablastSecurityHeaders
{
    /** @var array<string, string> */
    private $headers;
    /** @var string */
    private $nonce;

    public function __construct(SeablastConfiguration $configuration)
    {
        $this->nonce = base64_encode(random_bytes(24));
        $mode = $this->setting($configuration, SeablastConstant::SB_CSP_MODE, 'report-only');
        if (!in_array($mode, ['report-only', 'enforce', 'off'], true)) {
            throw new SeablastConfigurationException('Invalid CSP mode.');
        }
        $frames = $configuration->exists(SeablastConstant::SB_FRAME_ANCESTORS)
            ? $configuration->getArrayString(SeablastConstant::SB_FRAME_ANCESTORS) : ["'self'"];
        $this->validateFrames($frames);
        $framing = 'frame-ancestors ' . implode(' ', $frames);
        $this->headers = [
            'Cache-Control' => $this->setting($configuration, SeablastConstant::SB_CACHE_CONTROL, 'no-store'),
            'Content-Security-Policy' => $framing,
            'Referrer-Policy' => $this->setting(
                $configuration,
                SeablastConstant::SB_REFERRER_POLICY,
                'strict-origin-when-cross-origin'
            ),
            'X-Content-Type-Options' => 'nosniff',
        ];
        if ($frames === ["'self'"] || $frames === ["'none'"]) {
            $this->headers['X-Frame-Options'] = $frames === ["'self'"] ? 'SAMEORIGIN' : 'DENY';
        }
        $directives = self::defaultDirectives();
        if ($configuration->exists(SeablastConstant::SB_CSP_DIRECTIVES)) {
            $directives = array_replace(
                $directives,
                $configuration->getArrayArrayString(SeablastConstant::SB_CSP_DIRECTIVES)
            );
        }
        $policy = $this->contentPolicy($directives);
        $reportUri = $this->setting($configuration, SeablastConstant::SB_CSP_REPORT_URI, '', true);
        if ($reportUri !== '') {
            if (
                preg_match('~^(?:https://[^/\s;]+/|/(?!/))[^\s;]*$~D', $reportUri) !== 1
                || strpos($reportUri, '@') !== false
                || strpos($reportUri, '#') !== false
                || strpos($reportUri, '\\') !== false
            ) {
                throw new SeablastConfigurationException(
                    'CSP reporting requires a local path or HTTPS URL with a path.'
                );
            }
            $policy .= '; report-uri ' . $reportUri;
        }
        if ($mode === 'enforce') {
            $this->headers['Content-Security-Policy'] = $policy . '; ' . $framing;
        } elseif ($mode === 'report-only') {
            $this->headers['Content-Security-Policy-Report-Only'] = $policy;
        }
    }

    /** Own these header names; never remove cookies or unrelated application headers. */
    public function apply(): void
    {
        header_remove('Content-Security-Policy-Report-Only');
        header_remove('X-Frame-Options');
        foreach ($this->headers as $name => $value) {
            header($name . ': ' . $value, true);
        }
    }

    /** @param array<string[]> $directives */
    private function contentPolicy(array $directives): string
    {
        $parts = [];
        foreach ($directives as $name => $values) {
            if (
                !is_string($name) || preg_match('/^[a-z][a-z0-9-]*$/D', $name) !== 1
                || in_array($name, ['frame-ancestors', 'report-uri', 'report-to'], true)
            ) {
                throw new SeablastConfigurationException('Invalid or separately managed CSP directive.');
            }
            foreach ($values as $value) {
                if ($value === '' || preg_match('/[\x00-\x20\x7f;,]/', $value) === 1) {
                    throw new SeablastConfigurationException('CSP values must be individual tokens without controls.');
                }
                if (strpos($value, "'nonce-") === 0) {
                    throw new SeablastConfigurationException('CSP nonces are generated by the framework.');
                }
            }
            if (in_array("'none'", $values, true) && count($values) !== 1) {
                throw new SeablastConfigurationException('CSP none cannot be combined with other sources.');
            }
            if (in_array($name, ['script-src', 'style-src'], true) && $values !== ["'none'"]) {
                $values[] = "'nonce-" . $this->nonce . "'";
            }
            $parts[] = $name . ($values === [] ? '' : ' ' . implode(' ', $values));
        }
        return implode('; ', $parts);
    }

    /** @return array<string, string[]> */
    public static function defaultDirectives(): array
    {
        return [
            'default-src' => ["'self'"],
            'base-uri' => ["'self'"],
            'object-src' => ["'none'"],
            'script-src' => [
                "'self'",
                'https://ajax.googleapis.com/ajax/libs/jquery/3.7.1/jquery.min.js',
                'https://cdn.jsdelivr.net/gh/e3rd/WebHotkeys@0.9.4/WebHotkeys.js',
            ],
            'style-src' => ["'self'", 'https://fonts.googleapis.com/css2'],
            'font-src' => ["'self'", 'https://fonts.gstatic.com'],
        ];
    }

    /** @return array<string, string> */
    public function getHeaders(): array
    {
        return $this->headers;
    }

    public function getNonce(): string
    {
        return $this->nonce;
    }

    private function setting(
        SeablastConfiguration $configuration,
        string $key,
        string $default,
        bool $allowEmpty = false
    ): string {
        $value = $configuration->exists($key) ? $configuration->getString($key) : $default;
        if ((!$allowEmpty && trim($value) === '') || preg_match('/[\x00-\x1f\x7f]/', $value) === 1) {
            throw new SeablastConfigurationException('Invalid security header configuration.');
        }
        return $value;
    }

    /** @param string[] $frames */
    private function validateFrames(array $frames): void
    {
        if ($frames === [] || (in_array("'none'", $frames, true) && $frames !== ["'none'"])) {
            throw new SeablastConfigurationException('Invalid frame ancestor sources.');
        }
        foreach ($frames as $frame) {
            if ($frame === "'self'" || $frame === "'none'") {
                continue;
            }
            if (
                preg_match('~^https?://[a-zA-Z0-9.-]+(?::[0-9]{1,5})?$~D', $frame) !== 1
                || filter_var($frame, FILTER_VALIDATE_URL) === false
            ) {
                throw new SeablastConfigurationException(
                    'Frame ancestors require self, none, or explicit HTTP origins.'
                );
            }
        }
    }
}
